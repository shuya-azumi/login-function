<?php
// ============================================================
// funcs.php … 全ファイル共通で使う処理をまとめたファイル
// login.php や detail.php など、他のファイルから
// require_once('funcs.php'); で読み込んで使う
// ============================================================

// ------------------------------------------------------------
// 1) DB接続
// ------------------------------------------------------------
// Day3で学んだ「DB接続の4ブロックのうち1番目」を関数化したもの。
// これがないと、ファイルを増やすたびに同じ接続コードを
// コピペすることになり、パスワードを変更するときも
// 全ファイルを修正する羽目になる。
function db_conn()
{
    // DB接続情報はdb_config.phpから読み込む(環境ごとに書き換える)
    $config = require __DIR__ . '/db_config.php';
    try {
        $pdo = new PDO('mysql:dbname=' . $config['db_name'] . ';charset=utf8;host=' . $config['db_host'], $config['db_id'], $config['db_pw']);
        return $pdo;
    } catch (PDOException $e) {
        exit('DB Connection Error:' . $e->getMessage());
    }
}

// ------------------------------------------------------------
// 2) SQLエラー処理
// ------------------------------------------------------------
// $stmt->execute()が失敗したときに、毎回同じエラー表示コードを
// 書かなくていいようにまとめたもの。
function sql_error($stmt)
{
    $error = $stmt->errorInfo();
    exit('SQLError:' . print_r($error, true));
}

// ------------------------------------------------------------
// 3) リダイレクト
// ------------------------------------------------------------
// 処理が終わった後、別のページに飛ばす処理。
// header('Location: ...')の後は必ずexit()で処理を止める必要が
// あるが、これを忘れるバグが多いので関数にまとめて防止する。
function redirect($file_name)
{
    header('Location: ' . $file_name);
    exit();
}

// ------------------------------------------------------------
// 4) XSS対策(画面に出力する直前に必ず通す)
// ------------------------------------------------------------
// Day2で学んだ通り、DBから取得した値をそのままechoすると
// <script>タグなどを埋め込まれて悪意あるコードが実行されてしまう。
// echoする場所では必ずh()を通すのがルール。
function h($str)
{
    return htmlspecialchars($str, ENT_QUOTES, 'UTF-8');
}

// ------------------------------------------------------------
// 5) ログインチェック(今日の本題)
// ------------------------------------------------------------
// 会員専用ページ(detail.phpなど)の先頭で呼び出す。
// 「ログイン済みかどうか」をチェックし、未ログインなら
// その場で処理を止める。
//
// なぜ2つ条件があるのか:
// (1) isset(...) … そもそもログインした記録があるか
// (2) !== session_id() … その記録が「今のセッション」のものか
//     (古いセッションIDでのアクセスを弾くための保険)
function loginCheck()
{
    if (!isset($_SESSION['chk_ssid']) || $_SESSION['chk_ssid'] !== session_id()) {
        exit('LOGIN ERROR');
    } else {
        // 通過したら、セキュリティのためにセッションIDを更新しておく
        session_regenerate_id(true);
        $_SESSION['chk_ssid'] = session_id();
    }
}
