<?php
// ============================================================
// logout.php … ログアウト処理
// ============================================================
// ログインの「逆」の処理。SESSIONに記録した情報をすべて消して、
// 「誰でもない状態」に戻す。

session_start();

require_once('funcs.php');

// SESSIONの中身を空にする
$_SESSION = [];

// SESSION自体を破棄する
session_destroy();

// 一覧ページに戻す(ログアウトしたことが分かるように)
redirect('index.php');
